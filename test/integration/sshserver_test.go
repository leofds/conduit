func TestWrongPasswordRejected(t *testing.T) {
	requireSSHServer(t)

	cfg := &gossh.ClientConfig{
		User:            guestUser,
		Auth:            []gossh.AuthMethod{gossh.Password("wrong-password")},
		HostKeyCallback: gossh.InsecureIgnoreHostKey(), //nolint:gosec // test server
		Timeout:         5 * time.Second,
	}
	_, err := gossh.Dial("tcp", testAddr(), cfg)
	require.Error(t, err, "auth with a wrong password must fail")
}

