// Package main demonstrates embedding Conduit against the SSH sandbox that
// ships in test/sandbox (a real OpenSSH server running in a container).
//
// Start the sandbox first:
//
//	make sandbox-up        # generates keys if needed, listens on 127.0.0.1:2222
//
// Then run this example:
//
//	go run ./examples/sandbox
//
// Open http://localhost:9090/demo and connect to one of the hosts below:
//
//	test-master     password auth  (master / masterpass)
//	test-guest      password auth  (guest / guestpass)
//	test-key-master key auth       (master, private key on host)
//	test-key-guest  key auth       (guest, private key on host)
//	local           local shell session
//
// Host key verification is left on (TOFU), but auto-accept is enabled so the
// first connection does not prompt — convenient for automation. Fingerprints
// are persisted to a file so later restarts reuse them.
package main

import (
	"errors"
	"fmt"
	"log"
	"net/http"
	"os"
	"os/signal"
	"path/filepath"
	"syscall"

	conduit "github.com/leofds/conduit"
	"github.com/leofds/conduit/examples/internal/defaults"
	"github.com/leofds/conduit/knownhosts"
	"github.com/leofds/conduit/resolver"
)

const (
	sshAddr = "127.0.0.1"
	sshPort = "2222"

	// Path to the test keypair generated by `make sandbox-keys`.
	testKey = "test/sandbox/keys/authorized_keys.test"
)

// testResolver resolves the fixed set of hosts exposed by the test SSH server.
// All hosts share the container address/port; they differ only in credentials.
type testResolver struct {
	hosts map[string]resolver.SSHConfig
}

func (r testResolver) Resolve(req resolver.Request) (resolver.SessionConfig, error) {
	if req.Host == "local" {
		// Signal a local session; command/term come from the global defaults.
		return resolver.LocalConfig{}, nil
	}
	cfg, ok := r.hosts[req.Host]
	if !ok {
		return nil, fmt.Errorf("host %q not found", req.Host)
	}
	return cfg, nil
}

func main() {
	// Resolve the key path relative to the current working directory. When run
	// via `go run ./examples/sandbox` from the repo root this points at the
	// key generated by `make sandbox-keys`.
	keyPath, err := filepath.Abs(testKey)
	if err != nil {
		log.Fatalf("resolve key path: %v", err)
	}
	if _, err := os.Stat(keyPath); err != nil {
		log.Printf("warning: test key not found at %s (run 'make sandbox-keys'): %v", keyPath, err)
	}

	hosts := map[string]resolver.SSHConfig{
		// Password auth.
		"test-master": {Address: sshAddr, Port: sshPort, Username: "master"}, // password is masterpass
		"test-guest":  {Address: sshAddr, Port: sshPort, Username: "guest", Password: "guestpass"},

		// Key auth using the test keypair generated on the host.
		"test-key-master": {Address: sshAddr, Port: sshPort, Username: "master", PrivateKeyFile: keyPath},
		"test-key-guest":  {Address: sshAddr, Port: sshPort, Username: "guest", PrivateKeyFile: keyPath},
	}

	// Persist TOFU fingerprints to a file so restarts reuse them.
	provider, err := knownhosts.New("/tmp/conduit-example-known_hosts.yaml")
	if err != nil {
		log.Fatalf("known hosts: %v", err)
	}

	// Start from the standard defaults, then override what this example needs.
	opts := defaults.Options()
	opts.Resolver = testResolver{hosts: hosts}
	opts.KnownHosts = provider
	opts.SSH.AutoAcceptHostKey = true // skip the interactive TOFU prompt
	opts.SSH.VerifyHostKey = true     // still verify against the stored fingerprint

	srv, err := conduit.New(opts)
	if err != nil {
		log.Fatalf("create server: %v", err)
	}

	addr := ":9090"
	go func() {
		log.Printf("Starting conduit on %s (http://localhost%s/demo)", addr, addr)
		log.Printf("Test SSH server expected on %s:%s — start it with 'make sandbox-up'", sshAddr, sshPort)
		if err := srv.Start(addr); err != nil && !errors.Is(err, http.ErrServerClosed) {
			log.Fatalf("server error: %v", err)
		}
	}()

	quit := make(chan os.Signal, 1)
	signal.Notify(quit, syscall.SIGINT, syscall.SIGTERM)
	<-quit

	log.Println("Shutting down...")
	if err := srv.Shutdown(); err != nil {
		log.Fatalf("shutdown error: %v", err)
	}
	log.Println("Stopped")
}
